(**
  This file includes the abstract syntax of Core Erlang. It defines a number
  of notations and shorthands on top of this syntax. The syntax is defined in
  nameless variable representation.
 *)
From Stdlib Require Export ZArith.BinInt
                           Strings.String.
From stdpp Require Export list
                          bitvector.
From CoreErlang Require Export Basics.

Import ListNotations.

(** We use nats for process identifiers for simplicity. *)
Definition PID : Set := nat.

(** Currently, the only literals are integers and atoms. *)
Inductive Lit : Set :=
| Atom (s: string)
| Integer (x : Z)
(* | Float (q : R) *).

Coercion Atom : string >-> Lit.
Coercion Integer : Z >-> Lit.

(** Type, signedness and endianness specifiers of bitstring segments. *)
Inductive BinType :=
| IntType
| FloatType
| BinaryType
| BitstringType
| Utf8Type
| Utf16Type
| Utf32Type.
Inductive BinSign :=
| Signed
| Unsigned.
Inductive BinEnd :=
| BigEndian
| LittleEndian
| NativeEndian.

(** A bitstring segment: its value (`T1`), its size (`T2`), and the unit,
    type, signedness and endianness specifiers. In binary construction both
    the value and the size are expressions (`Segment Exp Exp`), while in
    binary patterns the value is a pattern and the size is a value
    (`Segment Pat Val`).
    The projections are prefixed with `seg_` so that they do not shadow
    `Datatypes.unit`, `stdpp.base.size`, etc. *)
Record Segment (T1 T2 : Type) := Build_Segment {
  seg_val : T1;
  seg_size : T2;
  seg_unit : nat;
  seg_type : BinType;
  seg_sign : BinSign;
  seg_endian : BinEnd
}.

Arguments Build_Segment {T1 T2} seg_val seg_size seg_unit seg_type seg_sign seg_endian.
Arguments seg_val {T1 T2} _.
Arguments seg_size {T1 T2} _.
Arguments seg_unit {T1 T2} _.
Arguments seg_type {T1 T2} _.
Arguments seg_sign {T1 T2} _.
Arguments seg_endian {T1 T2} _.

(**
  NOTE: to avoid potential issues with Prop-Type inconsistency, we still
  rely on manually written induction schemes (see `Induction.v`), and not
  on the ones generated by `Scheme All`.
  (Forall is not the same as list_all for this reason)
  Without `Scheme All` declarations for `list` and `prod`, Rocq warns
  ("<type> is nested using list/prod. No scheme for list/prod is
  registered as All.") when defining the syntax below; the following
  option silences this warning.
 *)
Set Warnings "-register-all".

(** Function identifiers: a (de Bruijn) index paired with the arity of the
    function. Renamings and substitutions only affect the index. *)
Definition FunId : Set := nat * nat.
(** Variables are (de Bruijn) indices. *)
Definition Var : Set := nat.

(** The following type represents Core Erlang expressions and values. It is
    mutually inductive, since function values include expressions as their body,
    moreover in a small-step semantics it is advantageous to have values as
    subexpressions.

    In OTP 23.0, receive expressions were removed from the language primitives,
    thus we don't need any other expression to express concurrency. Message
    receipts are expressed with primitive operations (see `EReceive` in
    `Concurrent/ProcessSemantics.v` for the derived form).
 *)
Inductive Exp : Set :=
| VVal (e : Val)
| EExp (e : NonVal)

with Val: Set := 
| VNil
| VLit    (l : Lit)
| VPid    (p : PID)
| VCons   (hd tl : Val)
| VTuple  (l : list Val)
| VMap    (l : list (Val * Val))
(** Value sequences are not included here, since they cannot be nested *)
| VVar    (n : Var)
| VFunId  (n : FunId)
(** Function normalforms: closures. These values contain:
     - a list of functions that can be applied recursively by the body expression
     - a function reference number
     - formal parameter count
     - the body *)
| VClos   (ext : list (nat * nat * Exp))
          (id : nat) (* Function reference number *)
          (params : nat) (* Parameter count *)
          (e : Exp)
| VBitstring (bits : bvn)

with NonVal : Set :=
| EFun    (vl : nat) (e : Exp)
| EValues (el : list Exp)
| ECons   (hd tl : Exp)
| ETuple  (l : list Exp)
| EMap    (l : list (Exp * Exp))
| ECall   (m f : Exp) (l : list Exp)
| EPrimOp (f : string)    (l : list Exp)
| EApp    (exp: Exp)     (l : list Exp)
| ECase   (e : Exp) (l : list ((list Pat) * Exp * Exp))
| ELet    (l : nat) (e1 e2 : Exp)
| ESeq    (e1 e2 : Exp)

| ELetRec (l : list (nat * Exp)) (e : Exp)
| ETry    (e1 : Exp) (vl1 : nat) (e2 : Exp) (vl2 : nat) (e3 : Exp)

(** Binary construction takes a list of arbitrary expressions, instead of a
    list of segments. Elements that are not segments (e.g., in `<<[]>>`) are
    not rejected syntactically, but they lead to a run-time error (the
    construction of the binary fails), similarly to Erlang. *)
| EBin (l : list Exp)
(** In Erlang, units can take a value between 1 and 256. This is not enforced
    syntactically (`seg_unit` is a `nat`). *)
| ESeg (seg : Segment Exp Exp)

(** Patterns of the language are its basic data structures (lists, tuples, maps),
    literals, and pattern variables. PIDs are _not_ patterns. Due to the
    nameless variable representation, pattern variables don't have a name,
    neither an index - their index is their position relative to each other in
    an inorder traversal of the pattern. *)
with Pat : Set :=
| PVar
(* | PPid (p : PID) *)
| PLit (l : Lit)
| PCons  (hd tl : Pat)
| PTuple (l : list Pat)
| PMap (l : list (Pat * Pat))
| PNil

(* An example for binary matching:
  <#{#<Seg1>(1,1,'integer',['unsigned'|['big']]),
     #<Seg2>(7,1,'integer',['unsigned'|['big']]),
     #<Rest>('all',1,'binary',['unsigned'|['big']])}#>  %% <-this matches the rest

   Sizes are guard expressions (i.e., 1, 7, and 'all'), not only
   integers/'all', according to https://www.erlang.org/doc/system/expressions.html#bit-syntax-expressions!

   Seemingly, the only three meaningful values of size are: integer, variable or 'all' - nested,
   hidden equality checks get unfolded by the compiler. However,
   we cannot only cover those, because substitutions could not be formalised.
   Substitutions would also need to replace these size variables inside
   patterns with values, therefore, mutual induction is not avoidable.

   However, all meaningful cases are covered if we use Vals. Testing shows
   that the compiler indeed allows values to be present as Size of binaries,
   but only the abovementioned values (variable, integer, or 'all') can result in
   successful matches.
 *)
| PBin (segments : list (Segment Pat Val)).

(** Injections of values (`˝`) and non-value expressions (`°`) into `Exp`. *)
Coercion EExp : NonVal >-> Exp.
Notation "˝ v" := (VVal v) (at level 11).
Notation "° n" := (EExp n) (at level 11).

(** A diverging program: a recursive function calling itself infinitely.
    It is used, e.g., in the termination and CIU proofs. *)
Definition inf :=
  ELetRec
    [(0, °EApp (˝VFunId (0, 0)) [])]
    (EApp (˝VFunId (0, 0)) []).

(** Shorthands: *)
Definition VEmptyMap : Val := VMap [].
Definition VEmptyTuple : Val := VTuple [].
Definition EEmptyMap : Exp := EMap [].
Definition EEmptyTuple : Exp := ETuple [].

(** The atom `error`, commonly used as a default value. *)
Definition ErrorVal : Val := (VLit (Atom "error"%string)).

