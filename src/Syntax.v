(** Exception classes in Erlang *)
Inductive ExcClass : Set :=
| Error | Throw | Exit.

(** Exception class to value conversion *)
Definition exclass_to_value (ex : ExcClass) : Val :=
match ex with
| Error => VLit (Atom "error"%string)
| Throw => VLit (Atom "throw"%string)
| Exit => VLit (Atom "exit"%string)
end.

(** Exceptions are triples, matching the three variables bound by the
    handler of a Core Erlang `try`:
    - Exception class
    - 1st Value : reason (the value matched by `catch Class:Reason`)
    - 2nd Value : an approximation of the stack trace. We do not model
      stack traces; where Erlang's topmost stack frame would record the
      arguments of the failing call (e.g., for `badarith`, `badarg`, `undef`),
      we store those, otherwise `VNil`. *)
Definition Exception : Set := ExcClass * Val * Val.

(** Commonly used exceptions: *)
Definition badarith (v : Val) : Exception :=
  (Error, VLit (Atom "badarith"%string), v).
Definition badarg (v : Val) : Exception :=
  (Error, VLit (Atom "badarg"%string), v).
(** In Erlang, the reasons of the following four exceptions are tuples:
    {badmap, Map}, {badkey, Key}, {badfun, F} and {badarity, {F, Args}} *)
Definition badmap (v : Val) : Exception :=
  (Error, VTuple [VLit (Atom "badmap"%string); v], VNil).
Definition badkey (v : Val) : Exception :=
  (Error, VTuple [VLit (Atom "badkey"%string); v], VNil).
Definition undef (v : Val) : Exception :=
  (Error, VLit (Atom "undef"%string), v).
Definition badfun (v : Val) : Exception :=
  (Error, VTuple [VLit (Atom "badfun"%string); v], VNil).
(** [args] is the argument list as an Erlang list value *)
Definition badarity (f args : Val) : Exception :=
  (Error, VTuple [VLit (Atom "badarity"%string); VTuple [f; args]], VNil).
Definition if_clause : Exception :=
  (Error, VLit (Atom "if_clause"%string), VNil).
Definition timeout_value v : Exception :=
  (Error, VLit (Atom "timeout_value"%string), v).

(** Value sequences: the result of a successful evaluation (exceptional
    results are expressed by `Redex` below). *)
Definition ValSeq := list Val.

(** Redexes are used in the frame stack semantics (which is a reduction-style
    semantics). `RBox` is used to express parameter list evaluation (i.e., in
    case of tuples, maps, applications, calls, primops) without code
    duplication.
  *)
Inductive Redex : Set :=
| RExp (e : Exp)
| RValSeq (vs : ValSeq)
| RExc (e : Exception)
| RBox.

(** Converting a list of functions into a list of closures. *)
Definition convert_to_closlist (l : list (nat * nat * Exp)) : (list Val) :=
  map (fun '(id,vc,e) => (VClos l id vc e)) l.
